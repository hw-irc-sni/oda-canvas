def serve_in_thread(app) -> tuple[uvicorn.Server, threading.Thread, str]:
    sock = socket.socket()
    sock.bind(("127.0.0.1", 0))
    server = uvicorn.Server(uvicorn.Config(app, log_level="warning"))
    thread = threading.Thread(target=server.run, kwargs={"sockets": [sock]}, daemon=True)
    thread.start()
    while not server.started:
        time.sleep(0.05)
    return server, thread, f"http://127.0.0.1:{sock.getsockname()[1]}"


def fake_model() -> FastAPI:
    """An OpenAI-compatible model route: 2-dimensional embeddings and an empty extraction."""
    app = FastAPI()

    @app.get("/v1/models")
    async def models():
        return {"data": [{"id": "e"}, {"id": "c"}]}

    @app.post("/v1/embeddings")
    async def embeddings(request: Request):
        texts = (await request.json())["input"]
        return {"data": [{"index": i, "embedding": [1.0, float(len(t) % 7) / 7]} for i, t in enumerate(texts)]}

    @app.post("/v1/chat/completions")
    async def chat():
        return {"choices": [{"message": {"content": "{\"entities\": [], \"relations\": [], \"attributes\": []}"}}]}
    return app


class Live:
    def __init__(self, postgres_url, qdrant_url, tmp_path):
        from app.db.session import make_engine

        async def reset():
            engine = make_engine(postgres_url)
            async with engine.begin() as conn:
                await conn.execute(text("DROP SCHEMA public CASCADE; CREATE SCHEMA public"))
            await engine.dispose()
        asyncio.run(reset())
        from qdrant_client import QdrantClient
        q = QdrantClient(url=qdrant_url)
        for c in q.get_collections().collections:
            q.delete_collection(c.name)
        self.model, self.model_thread, model_url = serve_in_thread(fake_model())
        (tmp_path / "token").write_text("internal-token")
        MOUNT.mkdir(parents=True, exist_ok=True)
        (MOUNT / "module.ttl").write_text(f"<{AS}Mounted> a <http://www.w3.org/2002/07/owl#Class> .")
        self.settings = Settings(
            component_name=CLIENT, store_path=str(tmp_path / "store"), database_url=postgres_url,
            keycloak_jwks_url="http://jwks.invalid/certs", keycloak_issuers=[ISSUER], qdrant_url=qdrant_url,
            federation_relay_port=0, internal_port=0, internal_host="127.0.0.1",
            internal_token_file=str(tmp_path / "token"), governance_require_validation=False, embedding_dimension=2,
            event_callback_allowed_hosts=["127.0.0.1"], event_poll_interval=3600, mount_roots=[str(MOUNT)],
            openai_base_url=f"{model_url}/v1", openai_chat_model="c", openai_embedding_model="e")
        self.app = create_app(self.settings, TokenValidator(self.settings, StaticJWKClient(KEY)))
        self.server, self.thread, root = serve_in_thread(self.app)
        self.base, self.process_base = root + self.settings.base_path, root + self.settings.process_base_path
        self.internal = f"http://127.0.0.1:{self.app.state.internal.port}"
        for _ in range(100):  # the model route is evaluated in the background at startup
            if self.app.state.models.active is not None:
                break
            time.sleep(0.05)

    def stop(self):
        for server, thread in ((self.server, self.thread), (self.model, self.model_thread)):
            server.should_exit = True
            thread.join(10)


def seed(live: Live) -> dict:
    c = httpx.Client(base_url=live.base, headers=auth(*ALL_ROLES), timeout=30)
    ttl = {"Content-Type": "text/turtle"}

    def ok(r):
        assert r.status_code < 300, (r.request.method, str(r.request.url), r.status_code, r.text)
        return r

    for mid, kind in [("as", "ontology"), ("as-shapes", "shapes"), ("br", "bridge"), ("del-mod", "ontology")]:
        ok(c.post("/knowledgeSpecification", json={"id": mid, "name": mid, "iri": f"https://example.org/{mid}/",
                                                   "specKind": kind, "layer": "Telecom", "prefix": mid.replace("-", ""),
                                                   "source": {"kind": "upload"}}))
    ok(c.put("/knowledgeSpecification/as/content", headers=ttl, content=f"""<{AS}Cell>
        a <http://www.w3.org/2002/07/owl#Class> ; <http://www.w3.org/2000/01/rdf-schema#label> "Cell" .
        <{AS}Site> a <http://www.w3.org/2002/07/owl#Class> . <{AS}on> a <http://www.w3.org/2002/07/owl#ObjectProperty> .
        """.encode()))
    ok(c.put("/knowledgeSpecification/as-shapes/content", headers=ttl, content=f"""
        <{AS}S> a <http://www.w3.org/ns/shacl#NodeShape> ; <http://www.w3.org/ns/shacl#targetClass> <{AS}Cell> .""".encode()))
    for mid in ("m-1", "m-del"):
        ok(c.post("/knowledgeSpecification/br/mapping", json={
            "id": mid, "subject": f"{AS}{mid}", "object": f"https://example.org/br/{mid}",
            "predicate": "http://www.w3.org/2004/02/skos/core#exactMatch"}))
    ok(c.post("/knowledgeSpecification/as/validation"))
    for kb, kind in [("kb", "hybrid"), ("del-kb", "graph")]:
        ok(c.post("/knowledge", json={"id": kb, "name": kb, "storeKind": kind, "conformsTo": [{"id": "as"}],
                                      "source": [{"kind": s} for s in ("upload", "tmf639", "tmf638", "tmf642",
                                                                       "tmf628", "tmf921", "remote")]}))
    ok(c.put("/knowledge/kb/graph", headers=ttl, content=f"<urn:c1> a <{AS}Cell> ; <{AS}on> <urn:s1> .".encode()))
    docs = [ok(c.post("/knowledge/kb/document", files={"file": (f"{n}.md", f"# {n}\n\ncell {n}".encode(),
                                                                 "text/markdown")})).json()["id"] for n in "abcd"]
    process = ok(c.post("/knowledge/kb/ingest", json={"documentId": [docs[0]]})).json()
    task = ok(c.get(f"{live.process_base}/process/{process['id']}")).json()["task"][0]["id"]
    ok(httpx.put(f"{live.internal}/internal/knowledge/kb/chunks", params={"source": docs[1]}, json={
        "chunks": [{"chunkId": f"{docs[1]}:0", "text": "cell b is down", "documentId": docs[1], "entityIri": ["urn:c1"]}],
        "dense": [[1.0, 0.5]]}, headers={"Authorization": "Bearer internal-token"}))
    rec = ok(c.post("/knowledge/kb/recommend", json={"iri": ["urn:c1"]})).json()
    hub = ok(c.post("/hub", json={"callback": "http://127.0.0.1:9/cb"})).json()
    proposal = ok(httpx.post(f"{live.internal}/internal/knowledge/kb/proposal", json={
        "source": "doc", "proposals": [{"kind": "dataConflict", "summary": "seed", "details": {"triples": []}}]},
        headers={"Authorization": "Bearer internal-token"})).json()["ids"][0]
    return {"documents": docs[1:3], "document": docs[2], "doc-del": docs[3], "process": process["id"], "task": task,
            "recommendation": rec["recommendationId"], "items": [i["itemId"] for i in rec["items"]],
            "hub": hub["id"], "proposal": proposal}


