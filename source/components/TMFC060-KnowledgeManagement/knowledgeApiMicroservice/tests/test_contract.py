"""Contract tests (schemathesis 4.33): every documented operation of the TMFxxx and TMF701 subset OAS, run over
HTTP against the real app (Postgres, Qdrant, a fake model route) with seeded data, must answer as the OAS says.
Run alone with `uv run pytest -m contract`.

- Positive pass: every check (no 5xx, documented status codes, content types, headers, response schemas, Allow,
  schema-valid requests accepted …) except those needing a stateful run.
- Negative pass: invalid requests must never cause a 5xx.
- Viewer pass: with a knowledge-viewer token, the answers (403s included) must still match the OAS.

Path parameters and references in bodies are pinned to seeded resources (DELETE gets throwaway copies). Syntax that
JSON Schema can't express is generated by strategies for the OAS custom formats (`turtle`, `sparql-query`,
`callback-url`, `iri-or-curie`) and for JSON-LD bodies. The callbacks (`/eventSource/…`, `/listener/…`) are not
generated: they are guarded by a secret URL, not a bearer token.
"""
