# ---- generation strategies for what JSON Schema can't express -------------------------------------------------
TURTLE = st.sampled_from([
    f"<urn:x:c{n}> a <{AS}Cell> ; <http://www.w3.org/2000/01/rdf-schema#label> \"cell {n}\" ." for n in range(5)
] + [f"@prefix as: <{AS}> . <urn:x:s1> a as:Cell ; as:on <urn:x:site{n}> ." for n in range(3)])
SPARQL = st.sampled_from([
    "SELECT ?s WHERE { ?s ?p ?o } LIMIT 5", f"ASK {{ ?s a <{AS}Cell> }}",
    f"SELECT ?c (COUNT(*) AS ?n) WHERE {{ ?c a <{AS}Cell> }} GROUP BY ?c",
    "CONSTRUCT { ?s ?p ?o } WHERE { ?s ?p ?o } LIMIT 3", "DESCRIBE <urn:c1>"])
CALLBACK = st.integers(0, 999).map(lambda n: f"http://127.0.0.1:9/cb/{n}")
TERM = st.sampled_from(TERMS)
JSONLD = st.sampled_from([{"@context": {"as": AS}, "@id": f"urn:x:j{n}", "@type": "as:Cell"} for n in range(4)]
                         + [{"@context": {"as": AS}, "@graph": [{"@id": "urn:x:j9", "as:on": {"@id": "urn:x:site9"}}]}])
# document uploads: content that matches the part's declared type (the API sniffs it)
N = st.integers(0, 10**6)
PDF = N.map(lambda n: b"%PDF-1.4\n1 0 obj << /Type /Catalog >> endobj\n% " + str(n).encode() + b"\n%%EOF\n")
MARKDOWN = N.map(lambda n: f"# Runbook {n}\n\nCheck the rectifier of site {n}.".encode())
HTML = N.map(lambda n: f"<html><body><h1>Runbook {n}</h1><p>Check site {n}.</p></body></html>".encode())
