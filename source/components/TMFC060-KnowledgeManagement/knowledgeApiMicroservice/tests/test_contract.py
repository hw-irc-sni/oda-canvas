@schemathesis.serializer("application/sparql-query")
def _sparql(ctx, value):
    """A query is text; negative data of another type goes as its JSON text."""
    if isinstance(value, bytes):
        return value
    return (value if isinstance(value, str) else json.dumps(value)).encode()


def load(name: str, mode: GenerationMode):
    schema = schemathesis.openapi.from_path(API / name).exclude(path_regex=CALLBACKS)
    schema.config.generation.update(modes=[mode], allow_x00=False)
    return schema


