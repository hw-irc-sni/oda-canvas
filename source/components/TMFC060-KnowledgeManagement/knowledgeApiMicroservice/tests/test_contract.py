# ---- pinning generated requests to the seeds --------------------------------------------------------------------
def pin(case) -> None:
    path, deleting = case.operation.path, case.method.upper() == "DELETE"
    params = dict(case.path_parameters or {})
    if "id" in params:
        if path.startswith("/knowledgeSpecification/"):
            params["id"] = ("br" if "/mapping" in path or path.endswith("/review") else "as-shapes" if path.endswith("/document")
                            else "del-mod" if deleting and path.count("/") == 2 else "as")
        elif path.startswith("/knowledge/"):
            params["id"] = "del-kb" if deleting and path.count("/") == 2 else "kb"
        else:
            params["id"] = SEEDS[{"/process/{id}": "process", "/task/{id}": "task", "/hub/{id}": "hub"}[path]]
    if "documentId" in params:
        params["documentId"] = SEEDS["doc-del" if deleting else "document"]
    if "proposalId" in params:
        params["proposalId"] = SEEDS["proposal"]
    if "mappingId" in params:
        params["mappingId"] = "m-del" if deleting else "m-1"
    if "name" in params:
        params["name"] = "FederatedKnowledgeSpecification.schema.json"
    case.path_parameters = params
    body = case.body
    if isinstance(body, dict):
        body = copy.deepcopy(body)
        for key in ("conformsTo", "imports"):
            if isinstance(body.get(key), list):
                body[key] = [{"id": "as"} for _ in body[key][:1]]
        if path.endswith("/ingest") and isinstance(body.get("documentId"), list):
            body["documentId"] = SEEDS["documents"][:len(body["documentId"])] if body["documentId"] else []
        source = body.get("source")
        if isinstance(source, dict) and source.get("kind") == "mount":  # under the deployment's mount roots
            source["path"] = str(MOUNT / "module.ttl")
        if "/mapping" in path:  # examples use prefixes the seeded modules don't declare
            for n, key in enumerate(("subject", "predicate", "object")):
                if key in body and body[key] not in TERMS:
                    body[key] = TERMS[n * 3 % len(TERMS)]
        if path.endswith("/review") and isinstance(body.get("target"), dict):
            body["target"]["id"] = "br" if body["target"].get("kind") == "module" else "m-1"
        if path == "/hub" and "callback" in body:  # examples name hosts that don't resolve
            body["callback"] = "http://127.0.0.1:9/cb"
        if path.endswith("/recommend/feedback"):
            body["recommendationId"] = SEEDS["recommendation"]
            body["itemId"] = SEEDS["items"][0] if SEEDS["items"] else "urn:c1"
        case.body = body


def run(case, base: str, roles=ALL_ROLES, checks=CHECK_LIST) -> None:
    pin(case)
    case.call_and_validate(base_url=base, headers=auth(*roles), checks=checks)


