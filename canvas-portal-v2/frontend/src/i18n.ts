export const languages = [
  { code: 'en', label: 'English' },
  { code: 'zh', label: '简体中文' },
] as const

export type Language = (typeof languages)[number]['code']

const translations: Partial<Record<Language, Record<string, string>>> = { zh }

export function currentLanguage(): Language {
  const saved = localStorage.getItem('canvas-portal-language')
  return languages.find((language) => language.code === saved)?.code ?? 'en'
}

export function t(text: string): string {
  return translations[currentLanguage()]?.[text] ?? text
}

export function setLanguage(language: Language): void {
  if (language === currentLanguage()) return
  localStorage.setItem('canvas-portal-language', language)
  window.location.reload()
}
